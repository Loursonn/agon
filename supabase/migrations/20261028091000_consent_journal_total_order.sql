/*
  Ordre total sur le journal de consentement.

  Problème : `current_consents` sélectionnait la décision courante avec
  `DISTINCT ON (user_id, purpose) ... ORDER BY created_at DESC`, sans
  départageur. Or `created_at` vaut `now()`, qui est l'heure de **début de
  transaction** et donc identique pour deux lignes écrites ensemble. Deux
  décisions à la même microseconde : laquelle est « la courante » devient
  l'ordre physique des lignes, c'est-à-dire indéterminé.

  Découvert en testant le retrait du consentement IA — un retrait écrit juste
  après un accord n'avait aucun effet visible une fois sur deux.

  Pourquoi ce n'est pas un détail de test : l'article 7.1 du RGPD demande de
  pouvoir *prouver* le consentement. Un journal dont on ne peut pas dire avec
  certitude quelle est la dernière décision ne prouve rien — et le sens de
  l'erreur est le pire possible, puisqu'un retrait peut rester sans effet.

  Correction : une colonne `seq` en `bigserial`. C'est exactement ce dont un
  journal en écriture seule a besoin — un ordre d'arrivée, indépendant de
  l'horloge et des transactions. On n'ordonne plus par le temps mais par la
  séquence ; `created_at` reste la donnée métier (quand la personne a décidé),
  `seq` devient la clé d'ordre (dans quel ordre elle a décidé).

  Table vide au moment de cette migration (vérifié : 0 ligne), donc aucun
  risque de renumérotation d'un historique existant.
*/

ALTER TABLE public.user_consents
  ADD COLUMN seq bigint GENERATED BY DEFAULT AS IDENTITY;

-- NOT NULL + UNIQUE : la clé d'ordre doit être totale. Une valeur manquante ou
-- dupliquée ramènerait exactement l'ambiguïté qu'on corrige.
ALTER TABLE public.user_consents
  ALTER COLUMN seq SET NOT NULL,
  ADD CONSTRAINT user_consents_seq_unique UNIQUE (seq);

COMMENT ON COLUMN public.user_consents.seq IS
  'Ordre d''arrivée dans le journal. Clé d''ordre de current_consents : created_at vaut now(), identique pour deux lignes d''une même transaction, donc insuffisant pour départager.';

CREATE OR REPLACE VIEW public.current_consents
WITH (security_invoker = true) AS
  SELECT DISTINCT ON (user_id, purpose)
         user_id,
         purpose,
         granted,
         doc_version,
         created_at AS decided_at
    FROM public.user_consents
   ORDER BY user_id, purpose, seq DESC;

COMMENT ON VIEW public.current_consents IS
  'Dernière décision par finalité. Ordonnée par seq et non par created_at : deux décisions d''une même transaction partagent le même created_at, ce qui rendait la décision courante indéterminée.';
